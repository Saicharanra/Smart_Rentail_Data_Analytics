/**
 * Returns a category-matched image URL for a given product or category index.
 */
export function getProductImageUrl(
  existingUrl?: string | null,
  categorySlugOrName?: string | null,
  index: number = 0
): string {
  const defaultHeadphone = 'https://images.unsplash.com/photo-1505740420928-5e560c06d30e?auto=format&fit=crop&w=800&q=80';
  
  // If existing URL is present and NOT the single over-used default, return it
  if (existingUrl && existingUrl.trim().length > 0 && existingUrl !== defaultHeadphone) {
    return existingUrl;
  }

  const slug = (categorySlugOrName || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

  const pool = CATEGORY_IMAGE_POOLS[slug];

  if (pool && pool.length > 0) {
    return pool[index % pool.length];
  }

  // Fall back to global image pool indexed by numeric ID/index
  return GLOBAL_PRODUCT_IMAGES[index % GLOBAL_PRODUCT_IMAGES.length];
}
